// 🚚 مصاريف الشحن: محافظات الصعيد ليها سعر مختلف عن باقي محافظات مصر
// (القاهرة والدلتا والوجه البحري وسيناء والبحر الأحمر). غيّري الأرقام أو
// انقلي محافظة من قايمة لأخرى من هنا بس، وكل حاجة (ملخص الطلب، الفاتورة،
// الطلب المُرسَل للباك إند) هتتحدث تلقائيًا.
export const SHIPPING_FEE_LOWER_EGYPT = 69; // القاهرة/الدلتا/الوجه البحري وما شابه
export const SHIPPING_FEE_UPPER_EGYPT = 99; // محافظات الصعيد

const UPPER_EGYPT_GOVERNORATES = new Set<string>([
  "الفيوم",
  "بني سويف",
  "المنيا",
  "أسيوط",
  "سوهاج",
  "قنا",
  "الأقصر",
  "أسوان",
  "الوادي الجديد",
]);

/** مصاريف الشحن المستحقة حسب المحافظة المُختارة. */
export function getShippingFee(governorate: string): number {
  return UPPER_EGYPT_GOVERNORATES.has(governorate)
    ? SHIPPING_FEE_UPPER_EGYPT
    : SHIPPING_FEE_LOWER_EGYPT;
}

